const PH: Record<string, [string, string]> = {};
const PAT: [RegExp, string, string][] = [];
PHR.forEach(([en, fr, ar]) => {
  if (en.includes('{0}')) {
    PAT.push([
      new RegExp('^' + en.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\{(\d)\}/g, '(.*?)') + '$'),
      fr,
      ar,
    ]);
  } else PH[en] = [fr, ar];
});

function tr(str: string, li: 0 | 1): string {
  const e = PH[str];
  if (e) return e[li];
  if (str.length < 2 || !/[A-Za-z]/.test(str)) return str;
  for (const [re, fr, ar] of PAT) {
    const m = str.match(re);
    if (m) {
      let out = li ? ar : fr;
      m.slice(1).forEach((g, i) => {
        out = out.split('{' + i + '}').join(tr(g, li));
      });
      return out;
    }
  }
  return str;
}

export type T = (en: string) => string;

/** Translator for a language; English (and unknown strings) pass through unchanged. */
export function makeT(lang: Lang): T {
  if (lang === 'EN') return (s) => s;
  const li = lang === 'FR' ? 0 : 1;
  return (s) => tr(s, li);
}
